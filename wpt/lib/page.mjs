// Loading a WPT test page into a window, for engines that do not load pages
// or run <script> elements themselves (warpdom; jsdom with scripts run from
// outside). Engine-neutral: it uses only DOM APIs and an engine adapter
// ({ window, evaluate(code, filename), reportError(error) }).
//
// The page is parsed with the engine's DOMParser, then moved node by node,
// in tree order, into the window's document, the way a parser inserts them:
// when a <script> element has been inserted, it runs before anything after
// it is inserted, so a script sees the elements before it and not those
// after it. Microtasks and pending tasks run between scripts. Deferred and
// async classic scripts and module scripts run after parsing, in document
// order. Then
// DOMContentLoaded fires at the document and load at the window (which
// testharness.js waits for).
//
// The document's mode (quirks without a doctype) is the parsed page's, for
// engines with a way to set it (warpdom). Not modeled: document.readyState transitions, document.currentScript,
// document.write, import maps, the parser's own error recovery while
// scripts run (the whole page is parsed first), stylesheets and images
// loading.
import { existsSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

export const ORIGIN = 'http://web-platform.test:8000';
export const HTTPS_ORIGIN = 'https://web-platform.test:8443';
const WPT_HOSTS = new Set(['web-platform.test', 'www.web-platform.test', 'www1.web-platform.test', 'www2.web-platform.test']);

// The HTML document WPT's server generates for foo.any.js and foo.window.js
// (documented under "testharness.js tests" > "Auto-generated test
// boilerplate").
export function wrapperHtml(test) {
  const meta = [];
  if (test.long) meta.push('<meta name="timeout" content="long">');
  if (test.title) meta.push(`<title>${escapeHtml(test.title)}</title>`);
  const scripts = (test.scripts ?? []).map((src) => `<script src="${escapeHtml(src)}"></script>`);
  const global = test.kind === 'any'
    ? '<script>\nself.GLOBAL = {\n  isWindow: function() { return true; },\n  isWorker: function() { return false; },\n  isShadowRealm: function() { return false; },\n};\n</script>\n'
    : '';
  const base = test.file.split('/').pop();
  return `<!doctype html>\n<meta charset=utf-8>\n${meta.join('\n')}\n${global}<script src="/resources/testharness.js"></script>\n<script src="/resources/testharnessreport.js"></script>\n${scripts.join('\n')}\n<div id=log></div>\n<script src="${escapeHtml(base)}"></script>\n`;
}

const escapeHtml = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

// wptserve's template substitutions (.sub. files), the subset that needs no
// server: hosts, ports, the request's query and location.
export function substitute(text, url) {
  const u = new URL(url);
  const ports = { http: ['8000', '8001'], https: ['8443', '8444'], ws: ['8888'], wss: ['8889'], 'h2': ['9000'] };
  return text.replace(/\{\{([^}]+)\}\}/g, (all, expr) => {
    expr = expr.trim();
    if (expr === 'host') return 'web-platform.test';
    let m;
    if ((m = /^domains\[([^\]]*)\]$/.exec(expr))) return m[1] ? `${m[1]}.web-platform.test` : 'web-platform.test';
    if ((m = /^hosts\[[^\]]*\]\[([^\]]*)\]$/.exec(expr))) return m[1] ? `${m[1]}.web-platform.test` : 'web-platform.test';
    if ((m = /^ports\[(\w+)\]\[(\d+)\]$/.exec(expr))) return ports[m[1]]?.[Number(m[2])] ?? all;
    if ((m = /^GET\[([^\]]*)\]$/.exec(expr))) return u.searchParams.get(m[1]) ?? '';
    if ((m = /^location\[(\w+)\]$/.exec(expr))) {
      const map = { host: u.host, hostname: u.hostname, port: u.port, scheme: u.protocol.slice(0, -1), path: u.pathname, query: u.search, server: u.origin, href: u.href, pathname: u.pathname };
      return map[m[1]] ?? all;
    }
    if (expr === 'uuid()') return crypto.randomUUID();
    return all;
  });
}

// Paths wptserve serves under another name (its routes).
const ALIASES = { '/resources/WebIDLParser.js': '/resources/webidl2/lib/webidl2.js' };

// The checkout file a same-origin URL maps to, or null (not a WPT host,
// generated by a Python handler, or missing).
export function wptFile(wptRoot, url) {
  if (!WPT_HOSTS.has(url.hostname)) return null;
  const path = ALIASES[url.pathname] ?? decodeURIComponent(url.pathname);
  if (path.endsWith('.py')) return null;
  const file = join(wptRoot, path);
  return existsSync(file) && statSync(file).isFile() ? file : null;
}

const MIME = { js: 'text/javascript', html: 'text/html', htm: 'text/html', css: 'text/css', json: 'application/json', xml: 'application/xml',
  xhtml: 'application/xhtml+xml', svg: 'image/svg+xml', txt: 'text/plain', idl: 'text/plain', png: 'image/png', gif: 'image/gif', jpg: 'image/jpeg' };

// A fetch() standing in for WPT's server: files of the checkout, by URL
// (relative URLs against the document's base URL); other origins fail as a
// network error. Static files only: no headers files, no Python handlers.
export function wptFetch(wptRoot, baseUrl) {
  return async function fetch(input, init) {
    const href = typeof input === 'string' ? input : input?.url ?? String(input);
    const url = new URL(href, baseUrl());
    if (!WPT_HOSTS.has(url.hostname)) throw new TypeError('Failed to fetch (network access is not available in this runner)');
    const file = wptFile(wptRoot, url);
    if (!file) return new Response('', { status: 404, statusText: 'Not Found' });
    const ext = file.split('.').pop();
    const response = new Response(readFileSync(file), { status: 200, headers: { 'content-type': MIME[ext] ?? 'application/octet-stream' } });
    Object.defineProperty(response, 'url', { value: url.href });
    return response;
  };
}

const JS_TYPES = new Set(['', 'text/javascript', 'application/javascript', 'application/ecmascript', 'application/x-ecmascript',
  'application/x-javascript', 'text/ecmascript', 'text/javascript1.0', 'text/javascript1.1', 'text/javascript1.2',
  'text/javascript1.3', 'text/javascript1.4', 'text/javascript1.5', 'text/jscript', 'text/livescript', 'text/x-ecmascript', 'text/x-javascript']);

// Elements whose children are moved with them (raw text, or content the
// parser builds before anything can observe it).
const KEEP_CHILDREN = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'TITLE', 'XMP', 'IFRAME', 'NOEMBED', 'NOFRAMES', 'NOSCRIPT', 'PLAINTEXT', 'OPTION']);

// Loads the test page into engine.window. host provides { yieldToTasks(),
// reporterSource, note(message) }. Returns when load has been dispatched.
export async function loadPage(engine, test, { wptRoot, reporterSource, yieldToTasks, note }) {
  const window = engine.window;
  const document = window.document;
  // Taken before any script runs: tests may delete interface objects
  // (dom/interface-objects.html deletes window.Event).
  const Event = window.Event;
  const testUrl = new URL(test.url, test.file.includes('.https.') ? HTTPS_ORIGIN : ORIGIN).href;
  let html = test.kind === 'html' ? readFileSync(join(wptRoot, test.file), 'utf8') : wrapperHtml(test);
  if (test.kind === 'html' && test.file.includes('.sub.')) html = substitute(html, testUrl);

  const parsed = new window.DOMParser().parseFromString(html, 'text/html');
  while (document.firstChild) document.removeChild(document.firstChild);
  engine.adoptDocumentMode?.(parsed);

  const later = []; // deferred and async classic scripts, in document order
  const baseUrl = () => (typeof document.baseURI === 'string' && document.baseURI !== 'about:blank' ? document.baseURI : testUrl);
  Object.defineProperty(engine.global, 'fetch', { value: wptFetch(wptRoot, baseUrl), writable: true, configurable: true, enumerable: false });

  function scriptSource(src) {
    let url;
    try { url = new URL(src, baseUrl()); } catch { return null; }
    if (!WPT_HOSTS.has(url.hostname)) return null;
    if (url.pathname === '/resources/testharnessreport.js') return { code: reporterSource, filename: url.href };
    const file = wptFile(wptRoot, url);
    if (!file) {
      note(`script not available: ${url.pathname}`);
      return null;
    }
    let code = readFileSync(file, 'utf8');
    if (/\.sub\.js$/.test(url.pathname)) code = substitute(code, url.href);
    return { code, filename: url.href };
  }

  function fire(target, type, init) {
    engine.fire(target, new Event(type, init));
  }

  function evaluate(code, filename) {
    try {
      engine.evaluate(code, filename);
    } catch (error) {
      engine.reportError(error);
    }
  }

  let inlineModules = 0;
  // Runs one script element: classic, or module (always deferred to after
  // parsing; async modules are not run earlier).
  async function execute(script, deferred) {
    const type = (script.getAttribute('type') ?? '').trim().toLowerCase();
    if (type === 'module') {
      if (!deferred) {
        later.push(script);
        return;
      }
      const src = script.getAttribute('src');
      const source = src != null ? scriptSource(src) : { code: script.textContent, filename: `${testUrl}#inline-module-${++inlineModules}` };
      if (!source) {
        fire(script, 'error');
        return;
      }
      try {
        await engine.evaluateModule(source.code, source.filename, (url) => scriptSource(url)?.code ?? null);
      } catch (error) {
        engine.reportError(error);
      }
      if (src != null) fire(script, 'load');
      await yieldToTasks();
      return;
    }
    if (!JS_TYPES.has(type)) return; // data blocks
    if (script.hasAttribute('src')) {
      if (!deferred && (script.hasAttribute('defer') || script.hasAttribute('async'))) {
        later.push(script);
        return;
      }
      const source = scriptSource(script.getAttribute('src'));
      if (!source) {
        fire(script, 'error');
      } else {
        evaluate(source.code, source.filename);
        fire(script, 'load');
      }
    } else {
      evaluate(script.textContent, testUrl);
    }
    await yieldToTasks();
  }

  // Moves the children of `from` into `to`, one at a time, in tree order.
  async function build(from, to) {
    for (let node = from.firstChild; node; node = from.firstChild) {
      const name = node.nodeType === 1 ? node.nodeName.toUpperCase() : '';
      let holder = null;
      if (node.nodeType === 1 && node.firstChild && !KEEP_CHILDREN.has(name)) {
        holder = parsed.createDocumentFragment();
        while (node.firstChild) holder.appendChild(node.firstChild);
      }
      to.appendChild(node);
      if (name === 'SCRIPT' && node.namespaceURI === 'http://www.w3.org/1999/xhtml') await execute(node, false);
      if (holder) await build(holder, node);
    }
  }

  await build(parsed, document);
  for (const script of later) await execute(script, true);
  fire(document, 'DOMContentLoaded', { bubbles: true });
  await yieldToTasks();
  fire(window, 'load');
  await yieldToTasks();
}

// The testharnessreport.js used in place of WPT's: disables the HTML
// output, applies the timeout multiplier and sends results to the host
// (a non-enumerable global set by the child process, removed here).
export function reporterSource() {
  return `(function () {
  var host = self.__wptHost;
  try { delete self.__wptHost; } catch (e) {}
  setup({ output: false, timeout_multiplier: host.timeoutMultiplier });
  add_result_callback(function (t) { host.result(t.name, t.status, t.message, t.stack); });
  add_completion_callback(function (tests, status) {
    host.complete(tests.map(function (t) { return [t.name, t.status, t.message, t.stack]; }), status.status, status.message, status.stack);
  });
})();
`;
}
