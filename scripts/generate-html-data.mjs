// Generates src/html-elements.js and src/html-reflect.js from the HTML
// standard's machine-readable data (dev dependencies):
// - @webref/elements: each HTML element's interface;
// - @webref/idl: interface inheritance, and the [Reflect...] extended
//   attributes marking IDL attributes that reflect content attributes.
//   node scripts/generate-html-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const { parse } = require('webidl2');
const idlDir = dirname(require.resolve('@webref/idl/package.json'));
const elements = require('@webref/elements/html.json').elements;
const ast = parse(readFileSync(join(idlDir, 'html.idl'), 'utf8'));

// --- interfaces and elements -----------------------------------------------------

const parents = new Map();
const members = new Map();
const mixins = new Map();
const includes = [];
for (const def of ast) {
  if (def.type === 'interface mixin') mixins.set(def.name, [...(mixins.get(def.name) ?? []), ...def.members]);
  else if (def.type === 'includes') includes.push(def);
  if (def.type !== 'interface' || !/^HTML\w*Element$/.test(def.name)) continue;
  if (!def.partial) parents.set(def.name, def.inheritance);
  members.set(def.name, [...(members.get(def.name) ?? []), ...def.members]);
}
// Members of included interface mixins (HTMLHyperlinkElementUtils, ...).
for (const { target, includes: mixin } of includes) {
  if (members.has(target)) members.set(target, [...members.get(target), ...(mixins.get(mixin) ?? [])]);
}

const tagsByInterface = new Map();
for (const { name, interface: iface } of elements) {
  if (!iface) continue;
  tagsByInterface.set(iface, [...(tagsByInterface.get(iface) ?? []), name]);
}

const plainTags = tagsByInterface.get('HTMLElement') ?? [];
const interfaces = [...parents.keys()].filter((name) => name !== 'HTMLElement');
// Parents before children.
const ordered = [];
const visit = (name) => {
  if (ordered.includes(name) || name === 'HTMLElement' || !parents.has(name)) return;
  visit(parents.get(name));
  ordered.push(name);
};
interfaces.forEach(visit);

writeFileSync(new URL('../src/html-elements.js', import.meta.url), `// Generated by scripts/generate-html-data.mjs from @webref/elements and
// @webref/idl (the HTML standard): HTML element interfaces with their parent
// and the tags that create them. Tags not listed create HTMLUnknownElement;
// PLAIN_TAGS create HTMLElement.
export const HTML_ELEMENTS = [
${ordered.map((name) => `  ${JSON.stringify([name, parents.get(name), (tagsByInterface.get(name) ?? []).sort()])},`).join('\n')}
];

export const PLAIN_TAGS = ${JSON.stringify(plainTags.sort())};
`);

// --- reflected attributes ----------------------------------------------------------

const ext = (member, name) => member.extAttrs.find((a) => a.name === name);
const argValue = (attr) => {
  if (!attr?.rhs) return undefined;
  const { type, value } = attr.rhs;
  if (type === 'string') return value.replace(/^"|"$/g, '');
  if (type === 'integer' || type === 'decimal') return Number(value);
  if (Array.isArray(value)) return value.map((v) => Number(v.value));
  return value;
};
const PRIMARY = ['Reflect', 'ReflectURL', 'ReflectNonNegative', 'ReflectPositive', 'ReflectPositiveWithFallback'];

// [property, content attribute, kind, options]
function reflection(member) {
  if (member.type !== 'attribute') return null;
  const primary = PRIMARY.map((name) => ext(member, name)).find(Boolean);
  if (!primary) return null; // includes [ReflectSetter]: the getter is custom
  const attr = argValue(primary) ?? member.name.toLowerCase();
  const type = member.idlType.idlType;
  const nullable = member.idlType.nullable;
  const options = {};
  const fallback = argValue(ext(member, 'ReflectDefault'));
  if (fallback !== undefined) options.default = fallback;
  const range = argValue(ext(member, 'ReflectRange'));
  if (range) options.range = range;
  if (primary.name === 'ReflectNonNegative') options.nonNegative = true;
  if (primary.name === 'ReflectPositive') options.positive = true;
  if (primary.name === 'ReflectPositiveWithFallback') options.positiveWithFallback = true;
  // [LegacyNullToEmptyString] on the type: null is set as ''.
  if (member.idlType.extAttrs?.some((a) => a.name === 'LegacyNullToEmptyString')) options.nullToEmpty = true;
  // USVString: lone surrogates become U+FFFD.
  if (type === 'USVString' && primary.name !== 'ReflectURL') options.usv = true;
  let kind;
  if (primary.name === 'ReflectURL') kind = 'url';
  else if (type === 'DOMString' || type === 'USVString') kind = nullable ? 'nullable' : 'string';
  else if (type === 'boolean') kind = 'boolean';
  else if (type === 'long') kind = 'long';
  else if (type === 'unsigned long') kind = 'unsigned';
  else if (type === 'double' || type === 'unrestricted double') kind = 'double';
  else if (type === 'DOMTokenList') kind = 'tokens';
  else return null; // element references and others: implemented by hand
  const entry = [member.name, attr, kind];
  if (Object.keys(options).length) entry.push(options);
  return entry;
}

const reflections = [];
for (const name of ['HTMLElement', ...ordered]) {
  const entries = (members.get(name) ?? []).map(reflection).filter(Boolean);
  if (entries.length) reflections.push([name, entries]);
}

// ARIA reflection (WAI-ARIA's ARIAMixin, included by Element): role and the
// aria-* attributes as nullable strings. Element-reference members are left
// to be implemented by hand.
const aria = parse(readFileSync(join(idlDir, 'wai-aria.idl'), 'utf8'));
const ariaEntries = aria.filter((d) => d.type === 'interface mixin' && d.name === 'ARIAMixin')
  .flatMap((d) => d.members).map(reflection).filter(Boolean);
reflections.unshift(['Element', ariaEntries]);

writeFileSync(new URL('../src/html-reflect.js', import.meta.url), `// Generated by scripts/generate-html-data.mjs from @webref/idl (the HTML
// standard's IDL): the IDL attributes HTML element interfaces reflect, from
// their [Reflect...] extended attributes. Entries:
// [property, content attribute, kind, options (default, range, nonNegative,
// positive, positiveWithFallback)].
export const REFLECTIONS = [
${reflections.map(([name, entries]) => `  [${JSON.stringify(name)}, [\n${entries.map((e) => `    ${JSON.stringify(e)},`).join('\n')}\n  ]],`).join('\n')}
];
`);

console.log(`${ordered.length} interfaces, ${elements.length} elements, ${reflections.reduce((n, [, e]) => n + e.length, 0)} reflected attributes`);

// --- event handlers ---------------------------------------------------------------------
// The event handler IDL attributes of the GlobalEventHandlers and
// WindowEventHandlers mixins, including
// partials from other specifications (pointer events, CSS animations, ...).

// (DocumentAndElementEventHandlers was folded into GlobalEventHandlers.)
const MIXINS = ['GlobalEventHandlers', 'WindowEventHandlers'];
const handlers = Object.fromEntries(MIXINS.map((m) => [m, new Set()]));
const { readdirSync } = await import('node:fs');
for (const file of readdirSync(idlDir).filter((f) => f.endsWith('.idl')).sort()) {
  let tree;
  try { tree = parse(readFileSync(join(idlDir, file), 'utf8')); } catch { continue; }
  for (const def of tree) {
    if (def.type !== 'interface mixin' || !MIXINS.includes(def.name)) continue;
    for (const m of def.members) {
      if (m.type === 'attribute' && /EventHandler$/.test(m.idlType.idlType)) handlers[def.name].add(m.name);
    }
  }
}

// Handlers for events warpdom never fires are left out (as in jsdom):
// libraries feature-detect them ('ontransitionend' in window, ...) and would
// wait for events that never come without layout, animations or devices.
// jsdom has the legacy onwebkitanimation* and onwebkittransitionend, so
// warpdom keeps them too.
const NEVER_FIRED = /^on(animation|transition|beforexrselect|command|fencedtreeclick|snapchang|selectionchange|selectstart|gamepad|pagereveal|pageswap|portalactivate)/;
for (const m of MIXINS) for (const name of handlers[m]) if (NEVER_FIRED.test(name)) handlers[m].delete(name);

writeFileSync(new URL('../src/event-handler-names.js', import.meta.url), `// Generated by scripts/generate-html-data.mjs from @webref/idl: event
// handler IDL attributes of the event handler interface mixins.
${MIXINS.map((m) => `export const ${m.replace(/^./, (c) => c.toUpperCase()).replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase()} = ${JSON.stringify([...handlers[m]].sort())};`).join('\n')}
`);
console.log(MIXINS.map((m) => `${m}: ${handlers[m].size}`).join(', '));
