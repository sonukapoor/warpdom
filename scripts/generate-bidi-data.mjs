// Generates src/bidi-data.js from the Unicode Character Database's
// DerivedBidiClass.txt: which code points have a strong bidirectional
// character type, L (left to right) or R/AL (right to left). The HTML
// standard's directionality (dir=auto, bdi, :dir()) needs nothing else.
//   node scripts/generate-bidi-data.mjs [path or URL of DerivedBidiClass.txt]
// Default: the latest UCD from unicode.org.
import { readFileSync, writeFileSync } from 'node:fs';

const source = process.argv[2] ?? 'https://www.unicode.org/Public/UCD/latest/ucd/extracted/DerivedBidiClass.txt';
const text = /^https?:/.test(source) ? await (await fetch(source)).text() : readFileSync(source, 'utf8');
const version = /^# DerivedBidiClass-([\d.]+)\.txt/m.exec(text)?.[1] ?? 'unknown';

// 0: not strong, 1: L, 2: R or AL.
const STRONG = { L: 1, Left_To_Right: 1, R: 2, Right_To_Left: 2, AL: 2, Arabic_Letter: 2 };
const cls = new Uint8Array(0x110000);
const apply = (from, to, name) => cls.fill(STRONG[name] ?? 0, from, to + 1);
const lines = text.split('\n');
// Defaults for unlisted code points (@missing lines, in file order), then the data.
for (const line of lines) {
  const m = /^# @missing: ([0-9A-F]+)\.\.([0-9A-F]+); (\w+)/.exec(line);
  if (m) apply(parseInt(m[1], 16), parseInt(m[2], 16), m[3]);
}
for (const line of lines) {
  const m = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)/.exec(line);
  if (m) apply(parseInt(m[1], 16), parseInt(m[2] ?? m[1], 16), m[3]);
}

// Runs of equal class: a class letter (N, L, R) and the run's start as a
// base-36 offset from the previous run's start.
let runs = '';
let prev = -1;
let prevStart = 0;
for (let cp = 0; cp < 0x110000; cp++) {
  if (cls[cp] === prev) continue;
  runs += 'NLR'[cls[cp]] + (cp - prevStart).toString(36);
  prev = cls[cp];
  prevStart = cp;
}

writeFileSync(new URL('../src/bidi-data.js', import.meta.url), `// Generated by scripts/generate-bidi-data.mjs from the Unicode Character
// Database ${version} (DerivedBidiClass.txt). Do not edit.
// Runs of code points with the same strong bidirectional character type:
// N (none), L (L), R (R or AL), each followed by its start as a base-36
// offset from the previous run's start.
export const BIDI_RUNS = '${runs}';
`);
console.log(`UCD ${version}: ${runs.length} characters`);
