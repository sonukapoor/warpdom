// Generates src/css-data.js from the CSS specifications' machine-readable
// data (@webref/css, a dev dependency): for each longhand property its
// initial value, whether it is inherited, whether its values can hold
// colors and whether a 0 in it is a length; each shorthand's longhands;
// legacy aliases. Also src/css-grammar.js: each property's value syntax and
// the syntax of the types and functions it uses, for value validation.
//   node scripts/generate-css-data.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { properties, types, functions } = require('@webref/css/css.json');

const byName = new Map(properties.map((p) => [p.name, p]));
const typeSyntax = new Map(types.map((t) => [t.name, t.syntax ?? '']));

// Does a value syntax reach <color>, directly or through the types
// (<shadow>) and properties (<'border-top-color'>) it refers to?
function holdsColor(syntax, seen = new Set()) {
  for (const [, quote, name] of syntax.matchAll(/<(')?([\w-]+)'?(?:\s*\[[^\]]*\])?>/g)) {
    if (!quote && (name === 'color' || name === 'paint')) return true;
    const key = (quote ? "'" : '') + name;
    if (seen.has(key)) continue;
    seen.add(key);
    const referenced = quote ? byName.get(name)?.syntax : typeSyntax.get(name);
    if (referenced && holdsColor(referenced, seen)) return true;
  }
  return false;
}

// Is a 0 in this syntax a length (computed as 0px)? When the syntax
// reaches <length> and does not also take a plain number (line-height: 0).
function zeroIsLength(syntax, seen = new Set()) {
  if (/<(number|integer)\b/.test(syntax)) return false;
  for (const [, quote, name] of syntax.matchAll(/<(')?([\w-]+)'?(?:\s*\[[^\]]*\])?>/g)) {
    if (!quote && (name === 'length' || name === 'length-percentage')) return true;
    const key = (quote ? "'" : '') + name;
    if (seen.has(key)) continue;
    seen.add(key);
    const referenced = quote ? byName.get(name)?.syntax : typeSyntax.get(name);
    if (referenced && zeroIsLength(referenced, seen)) return true;
  }
  return false;
}

// Initial values written as prose ("see individual properties", "depends
// on user agent") are not values.
const isValue = (initial) =>
  typeof initial === 'string' && !/\b(see|depends|n\/a|implementation|user agent)\b/i.test(initial);

const longhands = {};
const shorthands = {};
const aliases = {};
const colorShorthands = [];
for (const p of properties) {
  if (p.legacyAliasOf) {
    aliases[p.name] = p.legacyAliasOf;
    continue;
  }
  const color = holdsColor(p.syntax ?? '') ? 1 : 0;
  if (p.longhands) {
    shorthands[p.name] = p.longhands;
    if (color) colorShorthands.push(p.name);
    continue;
  }
  longhands[p.name] = [
    isValue(p.initial) ? p.initial : null,
    p.inherited === 'yes' ? 1 : 0,
    color,
    zeroIsLength(p.syntax ?? '') ? 1 : 0,
  ];
}

// Shorthands of shorthands (border → border-width → border-top-width).
const leaves = (name) => (shorthands[name] ? shorthands[name].flatMap(leaves) : [name]);
for (const name of Object.keys(shorthands))
  shorthands[name] = shorthands[name].flatMap(leaves).filter((n) => byName.has(n));

const out = `// Generated by scripts/generate-css-data.mjs from @webref/css. Do not edit.
// LONGHANDS: name -> [initial value or null, inherited (1/0), holds colors (1/0),
// a 0 is a length (1/0)].
export const LONGHANDS = ${JSON.stringify(longhands)};
// SHORTHANDS: name -> the longhands it sets, in the specification's order.
export const SHORTHANDS = ${JSON.stringify(shorthands)};
export const COLOR_SHORTHANDS = ${JSON.stringify(colorShorthands)};
// Legacy aliases (-webkit-flex-wrap -> flex-wrap).
export const ALIASES = ${JSON.stringify(aliases)};
`;
writeFileSync(new URL('../src/css-data.js', import.meta.url), out);
console.log(
  `${Object.keys(longhands).length} longhands, ${Object.keys(shorthands).length} shorthands, ${Object.keys(aliases).length} aliases`,
);

// --- value grammars ----------------------------------------------------------------------
// Property syntaxes, and the type and function syntaxes they reach. Types
// the specifications define in prose (<length>, <string>, ...) have none;
// css-values.js implements the primitive ones and treats the others as
// unknown (the property is then not validated).
const functionSyntax = new Map((functions ?? []).map((f) => [f.name, f.syntax ?? '']));
const propertySyntax = {};
for (const p of properties) {
  if (p.legacyAliasOf || !p.syntax) continue;
  propertySyntax[p.name] = p.syntax;
}
// Grammars as browsers (and jsdom) implement them, where the specification
// drafts differ: SVG 2's <paint> (fill: red; the Fill and Stroke draft's
// <paint> takes images), and values earlier drafts had that jsdom accepts.
const SVG_PAINT = 'none | <color> | <url> [ none | <color> ]? | context-fill | context-stroke';
Object.assign(propertySyntax, {
  fill: SVG_PAINT,
  stroke: SVG_PAINT,
  'fill-image': `[ ${SVG_PAINT} ]#`,
  'stroke-image': `[ ${SVG_PAINT} ]#`,
  // jsdom 28.1 and later (black box, the properties jsdom 27 and 28.0 do
  // not know): -webkit-user-select: contain is dropped, and the old flexbox
  // properties take their keywords. (-webkit-box-flex and
  // -webkit-box-ordinal-group take no plain number there, only calc():
  // not reproduced.)
  '-webkit-user-select': 'auto | text | none | all',
  '-webkit-box-align': 'start | end | center | baseline | stretch',
  '-webkit-box-orient': 'horizontal | vertical | inline-axis | block-axis',
  '-webkit-box-pack': 'start | end | center | justify',
});
const EXTRA_KEYWORDS = {
  'alignment-baseline': 'auto',
  zoom: 'normal',
  'text-emphasis-position': 'auto',
  'white-space': 'auto',
};
for (const [name, keyword] of Object.entries(EXTRA_KEYWORDS))
  propertySyntax[name] = `${keyword} | ${propertySyntax[name]}`;
const typesOut = {};
const pending = Object.values(propertySyntax);
const seenRefs = new Set();
while (pending.length) {
  const syntax = pending.pop();
  for (const [, quote, name] of syntax.matchAll(/<(')?([\w-]+(?:\(\))?)'?(?:\s*\[[^\]]*\])?>/g)) {
    if (quote || seenRefs.has(name)) continue;
    seenRefs.add(name);
    const referenced = name.endsWith('()') ? functionSyntax.get(name) : typeSyntax.get(name);
    if (referenced) {
      typesOut[name] = referenced;
      pending.push(referenced);
    }
  }
}
writeFileSync(
  new URL('../src/css-grammar.js', import.meta.url),
  `// Generated by scripts/generate-css-data.mjs from @webref/css. Do not edit.
// Value syntax (CSS Values 4, 2) of each property, and of the types and
// functions those reach. Types without an entry are defined in prose.
export const PROPERTY_SYNTAX = ${JSON.stringify(propertySyntax)};
export const TYPE_SYNTAX = ${JSON.stringify(typesOut)};
`,
);
console.log(
  `${Object.keys(propertySyntax).length} property syntaxes, ${Object.keys(typesOut).length} types and functions`,
);
