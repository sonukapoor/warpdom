// Generates the data at the end of src/encoding.js (between the
// "Generated" markers; one module loads faster than two) from the Encoding
// standard's data
// (https://encoding.spec.whatwg.org/): the encodings and their labels
// (encodings.json) and the index of every legacy single-byte encoding
// (index-<name>.txt).
//   node scripts/generate-encoding-data.mjs [base URL or directory]
// Default: the standard's site.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const base = process.argv[2] ?? 'https://encoding.spec.whatwg.org/';
const read = async (name) => {
  if (!/^https?:/.test(base)) return readFileSync(join(base, name), 'utf8');
  const response = await fetch(new URL(name, base));
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
  return response.text();
};
// ISO-8859-8-I decodes with ISO-8859-8's index (the standard has one index for both).
const INDEX = { 'iso-8859-8-i': 'iso-8859-8' };

const groups = JSON.parse(await read('encodings.json'));
// name (lowercase, as TextDecoder's encoding gives it) -> labels.
const labels = {};
const singleByte = {};
for (const group of groups) {
  for (const { name, labels: list } of group.encodings) {
    const key = name.toLowerCase();
    labels[key] = list;
    if (group.heading !== 'Legacy single-byte encodings') continue;
    // Pointers 0 to 127 are bytes 0x80 to 0xFF; unmapped pointers decode to
    // U+FFFD (an error when fatal), which no index maps to.
    const table = new Array(128).fill(0xfffd);
    for (const line of (await read(`index-${INDEX[key] ?? key}.txt`)).split('\n')) {
      const m = /^\s*(\d+)\s+0x([0-9A-F]+)/.exec(line);
      if (!m) continue;
      const code = parseInt(m[2], 16);
      if (code === 0xfffd) throw new Error(`${key} maps a pointer to U+FFFD`);
      table[Number(m[1])] = code;
    }
    singleByte[key] = table.map((c) => `\\u${c.toString(16).padStart(4, '0')}`).join('');
  }
}

const BEGIN = '// --- Generated by scripts/generate-encoding-data.mjs from the Encoding standard. Do not edit. ---';
const END = '// --- End of generated data. ---';
const data = `${BEGIN}
// ENCODING_LABELS: encoding name -> its labels (encodings.json).
const ENCODING_LABELS = ${JSON.stringify(labels)};
// SINGLE_BYTE: the code points of bytes 0x80 to 0xFF (index-<name>.txt);
// U+FFFD for unmapped bytes.
const SINGLE_BYTE = {
${Object.entries(singleByte).map(([k, v]) => `  '${k}': '${v}',`).join('\n')}
};
${END}`;
const file = new URL('../src/encoding.js', import.meta.url);
const source = readFileSync(file, 'utf8');
const from = source.indexOf(BEGIN);
const to = source.indexOf(END);
if (from === -1 || to === -1) throw new Error('src/encoding.js has no generated block');
writeFileSync(file, source.slice(0, from) + data + source.slice(to + END.length));
console.log(`src/encoding.js: ${Object.keys(labels).length} encodings, ${Object.values(labels).flat().length} labels, ${Object.keys(singleByte).length} single-byte indexes`);
