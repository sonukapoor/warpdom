// Measures, black box, how jsdom 31 expands shorthands, and writes
// src/css31-data.js. jsdom 31 has its own CSS engine and property data:
// its declaration blocks hold longhands only (CSSOM), and some of its
// shorthands differ from @webref's (src/css-data.js) in their longhands or
// their order (background has background-repeat-x and -y, vertical-align
// is a shorthand). For every property name warpdom's data or jsdom's
// style accessors know, the name is set to `initial` on an element's
// style, and the block's items are read:
// - one item, the name itself: a longhand;
// - several, or another name: a shorthand, its longhands in that order;
// - none: dropped.
// jsdom is only installed and run, never read.
//   node scripts/gen-css31.mjs            (jsdom31, the dev dependency)
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LONGHANDS, SHORTHANDS, ALIASES } from '../src/css-data.js';
import { STYLE_ACCESSORS } from '../src/css-properties.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'package.json'));
const { JSDOM } = require('jsdom31');
const { version } = require('jsdom31/package.json');
const window = new JSDOM('').window;

const dashed = (accessor) => {
  if (accessor === 'cssFloat') return 'float';
  const name = accessor.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
  return /^(webkit|moz|ms)-/.test(name) ? `-${name}` : name;
};
const MEMBERS = new Set(['cssText', 'length', 'parentRule']);
const names = new Set([...Object.keys(LONGHANDS), ...Object.keys(SHORTHANDS), ...Object.keys(ALIASES)]);
for (const accessor of STYLE_ACCESSORS) names.add(dashed(accessor));
let proto = Object.getPrototypeOf(window.document.body.style);
for (; proto && proto !== window.Object.prototype; proto = Object.getPrototypeOf(proto))
  for (const key of Object.getOwnPropertyNames(proto))
    if (
      /^[a-zA-Z]+$/.test(key) &&
      typeof Object.getOwnPropertyDescriptor(proto, key).get === 'function' &&
      !MEMBERS.has(key)
    )
      names.add(dashed(key));

const shorthands = {};
const longhands = [];
const dropped = [];
const aliases = {};
for (const name of [...names].sort()) {
  const style = window.document.createElement('div').style;
  style.setProperty(name, 'initial');
  const items = [];
  for (let i = 0; i < style.length; i++) items.push(style.item(i));
  if (items.length === 0) dropped.push(name);
  else if (items.length === 1 && items[0] === name) longhands.push(name);
  else if (items.length === 1 && style.cssText === `${items[0]}: initial;`) aliases[name] = items[0];
  else shorthands[name] = items;
}
// A shorthand whose block serializes as another name is an alias
// (-webkit-flex-flow is flex-flow).
for (const [name, items] of Object.entries(shorthands)) {
  const style = window.document.createElement('div').style;
  style.setProperty(name, 'initial');
  const written = style.cssText.slice(0, style.cssText.indexOf(':'));
  if (written !== name && shorthands[written]) {
    aliases[name] = written;
    delete shorthands[name];
  }
}

// One JSON string, parsed when a jsdom 31 window first needs it (css31.js):
// the other profiles pay only for scanning the literal.
const data = JSON.stringify({ shorthands, aliases, dropped });
writeFileSync(
  join(root, 'src/css31-data.js'),
  `// Generated by scripts/gen-css31.mjs (black box: jsdom ${version} run). Do not edit.
// shorthands: jsdom 31's shorthands -> their longhands, in the order its
// declaration blocks list them; aliases: names written as another
// (-webkit-transform is transform); dropped: names jsdom 31 does not keep.
export const DATA31 = ${JSON.stringify(data)};
`,
);
console.log(
  `${Object.keys(shorthands).length} shorthands, ${longhands.length} longhands, ${Object.keys(aliases).length} aliases, ${dropped.length} dropped`,
);
